"""Run the sweep of the long wave, moving pressure disturbances over the outer domain.

Each scenario is one disturbance of build_longwave_scenario.py, a pressure rise
of 200 Pa travelling along a track of 400 km through the Valletta harbours and
raised and lowered over 60 minutes. The sweep varies three quantities.

    speed       26, 29, 33, 36, 40 and 43 m/s, that is 94 to 155 km/h, the range
                resonant with the 70 to 190 m of the plateau
    heading     0 to 315 degrees at intervals of 45, the direction of travel
                clockwise from north
    length      standard deviation of 15 and 30 km along the track

That is 96 scenarios, each of 12 simulated hours, two-dimensional and
barotropic on the outer mesh. The scenarios are independent and are run
WORKERS at a time, each as a serial process. A scenario whose history file
exists is skipped, so an interrupted sweep is resumed by the same command.
The pressure file and the copy of the mesh are removed after each run, since
both are regenerated by the builder.

Usage:
    python run_longwave_sweep.py [--workers 6] [--list] [--mesh outer03] [--suffix _thd]
"""

from __future__ import annotations

import argparse
import itertools
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MESH = "outer03"
OUT = ROOT / "model" / "tests" / f"longwave_sweep_{MESH}"
SPEEDS = (26, 29, 33, 36, 40, 43)                 # m/s
HEADINGS = (0, 45, 90, 135, 180, 225, 270, 315)   # degrees, direction of travel
SIGMAS_KM = (15, 30)
T_TOTAL = 12 * 3600.0


def set_mesh(mesh: str, suffix: str = "") -> None:
    """Point the sweep at an outer mesh, each mesh and variant with its own directory of cases."""
    global MESH, OUT
    MESH = mesh
    # the sweep of 9 October on outer01 kept the directory without suffix
    name = "longwave_sweep" if mesh == "outer01" else f"longwave_sweep_{mesh}"
    OUT = ROOT / "model" / "tests" / (name + suffix)


def scenarios():
    for sigma, heading, speed in itertools.product(SIGMAS_KM, HEADINGS, SPEEDS):
        tag = f"_s{sigma:02d}"
        yield dict(case=f"{MESH}_h{heading:03d}_u{speed:02d}{tag}", sigma=sigma,
                   heading=heading, speed=speed, tag=tag)


def run_one(sc: dict) -> tuple[str, int, float]:
    his = OUT / sc["case"] / "output" / f"{sc['case']}_his.nc"
    if his.exists():
        return sc["case"], 0, 0.0
    t0 = time.time()
    cmd = [sys.executable, str(Path(__file__).with_name("build_longwave_scenario.py")),
           "--mesh", MESH, "--heading", str(sc["heading"]), "--speed", str(sc["speed"]),
           "--sigma-along", str(sc["sigma"] * 1e3), "--tag", sc["tag"],
           "--t-total", str(T_TOTAL), "--map-interval", "0", "--out", str(OUT),
           "--discard-inputs"]
    with open(OUT / f"{sc['case']}.log", "w") as log:
        rc = subprocess.call(cmd, stdout=log, stderr=subprocess.STDOUT)
    return sc["case"], rc if his.exists() else (rc or 1), time.time() - t0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--list", action="store_true", help="print the scenarios and stop")
    ap.add_argument("--mesh", default=MESH, help="outer mesh, outer01 or outer03")
    ap.add_argument("--suffix", default="", help="suffix of the directory of cases, e.g. _thd")
    args = ap.parse_args(argv)
    set_mesh(args.mesh, args.suffix)
    todo = list(scenarios())
    if args.list:
        for sc in todo:
            print(sc["case"])
        print(f"{len(todo)} scenarios")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    failed = 0
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        for n, (case, rc, wall) in enumerate(pool.map(run_one, todo), 1):
            failed += rc != 0
            print(f"{n:3d}/{len(todo)} {case} exit {rc} {wall:6.0f} s "
                  f"(elapsed {(time.time() - t0) / 60:.0f} min)", flush=True)
    print(f"done, {failed} failed, {(time.time() - t0) / 3600:.2f} h")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
